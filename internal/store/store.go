// Package store manages installed binaries under the cosmup home:
//
//	<root>/chains/<chain>/<version>/<daemon>   installed binaries
//	<root>/bin/<daemon>                        symlink to the active version
package store

import (
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/saadaltafofficial/cosmup/internal/installer"
)

type Store struct{ Root string }

// Default uses $COSMUP_HOME, falling back to ~/.cosmup.
func Default() (Store, error) {
	if r := os.Getenv("COSMUP_HOME"); r != "" {
		return Store{Root: r}, nil
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return Store{}, err
	}
	return Store{Root: filepath.Join(home, ".cosmup")}, nil
}

func (s Store) BinDir() string { return filepath.Join(s.Root, "bin") }

func (s Store) BinaryPath(chain, version, daemon string) string {
	return filepath.Join(s.Root, "chains", chain, version, daemon)
}

// Activate points bin/<daemon> at the given installed version. Usually that
// is a symlink. If the version folder holds shared libraries the binary
// loads at startup (e.g. libwasmvm), it is instead a small wrapper script
// that adds the folder to the library path. Either way it is swapped in with
// a rename, so it is never missing mid-switch.
func (s Store) Activate(chain, version, daemon string) error {
	target := s.BinaryPath(chain, version, daemon)
	if _, err := os.Stat(target); err != nil {
		return fmt.Errorf("%s %s is not installed (run: cosmup install %s@%s)", chain, version, chain, version)
	}
	if err := os.MkdirAll(s.BinDir(), 0o755); err != nil {
		return err
	}
	link := filepath.Join(s.BinDir(), daemon)
	tmp := link + ".tmp"
	os.Remove(tmp)
	libs, err := SharedLibs(filepath.Dir(target))
	if err != nil {
		return err
	}
	if len(libs) == 0 {
		err = os.Symlink(target, tmp)
	} else {
		err = os.WriteFile(tmp, []byte(wrapperScript(target)), 0o755)
	}
	if err != nil {
		return err
	}
	return os.Rename(tmp, link)
}

// wrapperMarker starts the line in a wrapper script that names its target.
const wrapperMarker = "# cosmup-target: "

func wrapperScript(target string) string {
	q := shellQuote(filepath.Dir(target))
	return "#!/bin/sh\n" +
		"# Generated by cosmup. Runs the binary with the shared libraries installed next to it.\n" +
		wrapperMarker + target + "\n" +
		"dir=" + q + "\n" +
		"LD_LIBRARY_PATH=\"$dir${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}\" \\\n" +
		"DYLD_LIBRARY_PATH=\"$dir${DYLD_LIBRARY_PATH:+:$DYLD_LIBRARY_PATH}\" \\\n" +
		"\texec \"$dir/" + filepath.Base(target) + "\" \"$@\"\n"
}

func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// SharedLibs lists the shared libraries in a version folder.
func SharedLibs(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var libs []string
	for _, e := range entries {
		if e.Type().IsRegular() && installer.IsSharedLib(e.Name()) {
			libs = append(libs, e.Name())
		}
	}
	return libs, nil
}

// Installation is one installed version of a chain.
type Installation struct {
	Chain, Version, Daemon string
	Active                 bool
}

// Installed lists everything under chains/, sorted by chain then version.
func (s Store) Installed() ([]Installation, error) {
	var out []Installation
	chainsDir := filepath.Join(s.Root, "chains")
	chains, err := os.ReadDir(chainsDir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	for _, c := range chains {
		versions, err := os.ReadDir(filepath.Join(chainsDir, c.Name()))
		if err != nil {
			return nil, err
		}
		for _, v := range versions {
			files, err := os.ReadDir(filepath.Join(chainsDir, c.Name(), v.Name()))
			if err != nil {
				return nil, err
			}
			for _, f := range files {
				// Skip hidden files and shared libraries bundled with the binary.
				if f.Type().IsRegular() && !strings.HasPrefix(f.Name(), ".") && !installer.IsSharedLib(f.Name()) {
					out = append(out, Installation{
						Chain: c.Name(), Version: v.Name(), Daemon: f.Name(),
						Active: s.isActive(c.Name(), v.Name(), f.Name()),
					})
				}
			}
		}
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Chain != out[j].Chain {
			return out[i].Chain < out[j].Chain
		}
		return out[i].Version < out[j].Version
	})
	return out, nil
}

func (s Store) isActive(chain, version, daemon string) bool {
	return s.activeTarget(daemon) == s.BinaryPath(chain, version, daemon)
}

// activeTarget is the binary bin/<daemon> runs: a symlink's target, or the
// target recorded in a cosmup wrapper script. "" if neither.
func (s Store) activeTarget(daemon string) string {
	link := filepath.Join(s.BinDir(), daemon)
	if target, err := os.Readlink(link); err == nil {
		return target
	}
	f, err := os.Open(link)
	if err != nil {
		return ""
	}
	defer f.Close()
	head := make([]byte, 4096)
	n, _ := io.ReadFull(f, head)
	for _, line := range strings.Split(string(head[:n]), "\n") {
		if t, ok := strings.CutPrefix(line, wrapperMarker); ok {
			return t
		}
	}
	return ""
}

// Remove deletes one installed version and returns the bytes it freed. If
// that version is active, its bin/ link is removed too. An emptied chain
// folder is removed as well.
func (s Store) Remove(in Installation) (int64, error) {
	dir := filepath.Dir(s.BinaryPath(in.Chain, in.Version, in.Daemon))
	size, err := dirSize(dir)
	if err != nil {
		return 0, err
	}
	if s.isActive(in.Chain, in.Version, in.Daemon) {
		if err := os.Remove(filepath.Join(s.BinDir(), in.Daemon)); err != nil {
			return 0, err
		}
	}
	if err := os.RemoveAll(dir); err != nil {
		return 0, err
	}
	chainDir := filepath.Dir(dir)
	if entries, err := os.ReadDir(chainDir); err == nil && len(entries) == 0 {
		os.Remove(chainDir)
	}
	return size, nil
}

// InstalledAt is when a version was installed (its folder's mtime).
func (s Store) InstalledAt(in Installation) time.Time {
	st, err := os.Stat(filepath.Dir(s.BinaryPath(in.Chain, in.Version, in.Daemon)))
	if err != nil {
		return time.Time{}
	}
	return st.ModTime()
}

func dirSize(dir string) (int64, error) {
	var total int64
	err := filepath.WalkDir(dir, func(_ string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.Type().IsRegular() {
			info, err := d.Info()
			if err != nil {
				return err
			}
			total += info.Size()
		}
		return nil
	})
	return total, err
}
